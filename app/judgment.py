def generate(
    m: Meishiki,
    r: ShozanReading,
    *,
    name: Optional[str] = None,
    sex: Optional[Sex] = None,
    use_cache: bool = True,
) -> str:
    """命式＋象山流鑑定要素＋（任意で）名前から鑑定文を生成。"""
    key = _meishiki_key(m, name, sex)
    cache_path = CACHE_DIR / f"{key}.txt"
    if use_cache and cache_path.exists():
        log.info("judgment cache hit: %s", key)
        return cache_path.read_text(encoding="utf-8")

    payload = _build_payload(m, r, name, sex)
    log.info("judgment cache miss, calling Claude (model=%s, key=%s)", MODEL, key)

    client = anthropic.Anthropic()
    response = client.messages.create(
        model=MODEL,
        max_tokens=4000,
        system=[
            {
                "type": "text",
                "text": SYSTEM_PROMPT,
                "cache_control": {"type": "ephemeral"},
            }
        ],
        messages=[{"role": "user", "content": payload}],
    )

    log.info(
        "judgment usage: input=%d, cache_read=%d, cache_create=%d, output=%d",
        response.usage.input_tokens,
        response.usage.cache_read_input_tokens or 0,
        response.usage.cache_creation_input_tokens or 0,
        response.usage.output_tokens,
    )

    text = next((b.text for b in response.content if b.type == "text"), "").strip()
    if not text:
        raise RuntimeError("Claude returned empty text")

    if use_cache:
        cache_path.write_text(text, encoding="utf-8")
    return text
