def _meishiki_key(m: Meishiki, name: Optional[str], sex: Optional[Sex]) -> str:
    pillars = [(p.tengan, p.chishi) for p in m.pillars]
    payload = {"pillars": pillars, "name": name, "sex": sex}
    raw = json.dumps(payload, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:16]


def _format_pillar(p, nikkan: str) -> str:
    from .shozan import juniun
    tg_t = p.tengan_tsuhensei or "（日主）"
    ju = juniun(nikkan, p.chishi)
    if p.zokan_tsuhensei:
        zokan = "、".join(f"{z}({t})" for z, t in zip(p.zokan, p.zokan_tsuhensei))
    else:
        zokan = "、".join(p.zokan)
    return f"- {p.name}: {p.tengan}{p.chishi}（天干通変:{tg_t}、十二運:{ju}、蔵干:{zokan}）"


def _build_payload(
    m: Meishiki,
    r: ShozanReading,
    name: Optional[str],
    sex: Optional[Sex],
) -> str:
    lines = []
    lines.append("# 命式")
    lines.append(
        f"日干: {m.nikkan}（{m.nikkan_gogyo}・{m.nikkan_yinyang}・{r.mikyojaku.label}）"
    )
    for p in m.pillars:
        lines.append(_format_pillar(p, m.nikkan))
    # 4柱目が無い場合
    if len(m.pillars) < 4:
        lines.append("- 時柱: 不明")
    lines.append("")

    lines.append("# 五行バランス")
    gogyo_str = " ".join(f"{g}:{c}" for g, c in r.gogyo_counts.items())
    miss = "、".join(r.missing) if r.missing else "なし"
    lines.append(f"{gogyo_str}（欠落: {miss}）")
    lines.append("")

    lines.append("# 吉神・凶神・空亡")
    lines.append(
        f"華蓋:{'有' if r.kagai else '無'}、"
        f"天徳貴人:{'有' if r.tentoku else '無'}、"
        f"月徳貴人:{'有' if r.gettoku else '無'}、"
        f"天乙貴人:{'有' if r.tenotsu else '無'}、"
        f"将星:{'有' if r.shosei else '無'}、"
        f"桃花:{'有' if r.touka else '無'}、"
        f"羊刃:{'有' if r.yojin else '無'}、"
        f"紅艶:{'有' if r.koen else '無'}、"
        f"空亡:{r.kuubou[0]}・{r.kuubou[1]}"
    )
    lines.append("")

    lines.append("# 調候用神")
    lines.append(r.chouko or "該当なし（標準テーブル外）")
    lines.append("")

    lines.append("# 大運")
    for d in r.daiun_list:
        lines.append(
            f"{d.age_from:2d}才〜{d.age_to:2d}才: {d.tengan}{d.chishi}（{d.tsuhensei}・{d.juniun}）"
        )

    if r.nenmawari_list:
        lines.append("")
        lines.append("# 年廻り（今年〜)")
        for n in r.nenmawari_list:
            lines.append(
                f"{n.year}({n.age}才): {n.nen_kanshi} 十二運={n.juniun} → {n.label}"
            )

    if r.tsukimawari_list:
        lines.append("")
        lines.append("# 月廻り（今月から12ヶ月）")
        for tk in r.tsukimawari_list:
            lines.append(
                f"{tk.year}年{tk.month:2d}月({tk.age}才): {tk.getsu_kanshi} 十二運={tk.juniun} → {tk.label}"
            )

    if name:
        lines.append("")
        lines.append("# 名前")
        sex_label = {"M": "男性", "F": "女性"}.get(sex or "", "性別不明")
        lines.append(f"{name}（{sex_label}）")

    return "\n".join(lines)


def extract_section(full_text: str, section_number: int) -> str:
    """鑑定文全文から指定セクション（例: 3 → '## 3. 性格傾向'）を抽出。

    9セクション構成（システムプロンプトで定義）の各セクションを切り出すヘルパー。
    フリーミアム実装で「無料ユーザーには性格傾向だけ」を返すときに使う。

    指定セクションが見つからなければ空文字を返す。
    """
    import re
    # ## N. ... から次の ## または末尾までを抽出
    pattern = rf"##\s*{section_number}\.[^\n]*\n(.*?)(?=\n##\s|\Z)"
    match = re.search(pattern, full_text, re.DOTALL)
    if not match:
        return ""
    # ヘッダ行も含めて返す
    header_match = re.search(rf"##\s*{section_number}\.[^\n]*", full_text)
    header = header_match.group(0) if header_match else ""
    body = match.group(1).strip()
    return f"{header}\n\n{body}"


